use super::engine::get_shield_manager;

const PROCEDURAL_PSEUDO_MARKERS: &[&str] = &[
    ":has-text(",
    ":upward(",
    ":xpath(",
    ":matches-css(",
    ":matches-css-before(",
    ":matches-css-after(",
    ":matches-attr(",
    ":matches-path(",
    ":min-text-length(",
];

/// Filter out non-standard uBO/Brave procedural pseudo-classes so they don't pollute CSS stylesheets.
fn filter_css_selectors(selectors: &[String]) -> Vec<&str> {
    selectors
        .iter()
        .map(|s| s.trim())
        .filter(|s| {
            !s.is_empty()
                && !PROCEDURAL_PSEUDO_MARKERS
                    .iter()
                    .any(|marker| s.contains(marker))
        })
        .collect()
}

/// Build a stylesheet with one rule per selector so a single unsupported selector
/// never causes the browser's CSS parser to discard the remaining rules.
fn build_cosmetic_css(selectors: &[&str]) -> String {
    let mut css = String::new();
    for sel in selectors {
        css.push_str(sel);
        css.push_str(" { display: none !important; visibility: hidden !important; height: 0 !important; }\n");
    }
    css
}

/// Dynamically injects site-specific cosmetic CSS hide selectors for any page via adblock-rust
pub fn inject_page_cosmetics(webview: &tauri::Webview, tab_id: &str, url: &str) {
    let manager = get_shield_manager();
    if !manager.is_enabled() {
        return;
    }
    let cosmetic = manager.url_cosmetic_resources(url);
    if !cosmetic.hide_selectors.is_empty() {
        let raw_selectors: Vec<String> = cosmetic.hide_selectors.into_iter().collect();
        let valid_selectors = filter_css_selectors(&raw_selectors);
        if valid_selectors.is_empty() {
            return;
        }
        let css_json = serde_json::to_string(&build_cosmetic_css(&valid_selectors))
            .unwrap_or_else(|_| "\"\"".to_string());
        let selectors_json = serde_json::to_string(&valid_selectors)
            .unwrap_or_else(|_| "[]".to_string());
        let tab_id_json = serde_json::to_string(tab_id).unwrap_or_else(|_| "\"\"".to_string());
        let css_injection = format!(
            r#"(function() {{
                var s = document.getElementById("yoonspace-page-cosmetic");
                if (!s) {{
                    s = document.createElement("style");
                    s.id = "yoonspace-page-cosmetic";
                    (document.head || document.documentElement).appendChild(s);
                }}
                s.textContent = {css_json};
                try {{
                    var sels = {selectors_json};
                    var count = 0;
                    for (var i = 0; i < sels.length; i++) {{
                        try {{
                            count += document.querySelectorAll(sels[i]).length;
                        }} catch (e) {{}}
                    }}
                    if (count > 0 && window.webkit && window.webkit.messageHandlers && window.webkit.messageHandlers.shield_block) {{
                        window.webkit.messageHandlers.shield_block.postMessage(JSON.stringify({{
                            tabId: {tab_id_json},
                            url: "cosmetic://" + window.location.hostname + "/ad-elements",
                            category: "ad",
                            count: count
                        }}));
                    }}
                }} catch (e) {{}}
            }})();"#,
            css_json = css_json,
            selectors_json = selectors_json,
            tab_id_json = tab_id_json
        );
        let _ = webview.eval(&css_injection);
    }
}

